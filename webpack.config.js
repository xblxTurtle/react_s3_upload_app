import path from "node:path";
import { fileURLToPath } from "node:url";
import webpack from "webpack";

// In Node.js versions prior to native support for import.meta.dirname,
// derive __dirname from import.meta.url.
// (Node 20.11+ supports import.meta.dirname and import.meta.filename.)
const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

export default {
  entry: "./src/index.js",
  output: {
    filename: "main.js",
    path: path.resolve(__dirname, "dist"),
  },
  resolve: {
    extensions: [".js", ".jsx"],
  },
  module: {
    rules: [
      {
        test: /\.(js|jsx)$/,
        exclude: /node_modules/,
        use: "babel-loader",
      },
    ],
  },
  plugins: [
    new webpack.DefinePlugin({
      UPLOAD_BUCKET_NAME: process.env.UPLOAD_BUCKET_NAME,
      PRESIGN_UPLOAD_URL: process.env.PRESIGN_UPLOAD_URL
    })
  ],
};